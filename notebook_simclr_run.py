def noisify_cifar10_asymmetric(y_train, noise, seed=None):
    """mistakes:
        automobile <- truck
        bird -> airplane
        cat <-> dog
        deer -> horse
    """
    nb_classes = 10
    P = np.eye(nb_classes)
    n = noise

    if n > 0.0:
        # automobile <- truck
        P[9, 9], P[9, 1] = 1. - n, n

        # bird -> airplane
        P[2, 2], P[2, 0] = 1. - n, n

        # cat <-> dog
        P[3, 3], P[3, 5] = 1. - n, n
        P[5, 5], P[5, 3] = 1. - n, n

        # automobile -> truck
        P[4, 4], P[4, 7] = 1. - n, n

        y_train_noisy = multiclass_noisify(y_train,
                                           P=P,
                                           seed=seed)
        actual_noise = (y_train_noisy != y_train).mean()
        assert actual_noise > 0.0
        print('Actual noise %.2f' % actual_noise)
        y_train = y_train_noisy

    return y_train, P


def noisify_cifar100_asymmetric(y_train, noise, seed=None):
    """mistakes are inside the same superclass of 10 classes, e.g. 'fish'
    """
    nb_classes = 100
    P = np.eye(nb_classes)
    n = noise
    nb_superclasses = 20
    nb_subclasses = 5

    if n > 0.0:
        for i in np.arange(nb_superclasses):
            init, end = i * nb_subclasses, (i + 1) * nb_subclasses
            P[init:end, init:end] = build_for_cifar100(nb_subclasses, n)

        y_train_noisy = multiclass_noisify(y_train,
                                           P=P,
                                           seed=seed)
        actual_noise = (y_train_noisy != y_train).mean()
        assert actual_noise > 0.0
        print('Actual noise %.2f' % actual_noise)
        y_train = y_train_noisy

    return y_train, P


def noisify(dataset='mnist',
            nb_classes=10,
            train_labels=None,
            noise_type=None,
            noise_rate=0,
            random_state=0,
            seed=0):
    if noise_type == 'pairflip':
        train_noisy_labels, actual_noise_rate = noisify_pairflip(
            train_labels,
            noise_rate,
            seed=seed,
            nb_classes=nb_classes)
    if noise_type == 'sym':
        train_noisy_labels, actual_noise_rate = noisify_multiclass_symmetric(
            train_labels,
            noise_rate,
            seed=seed,
            nb_classes=nb_classes)
    if noise_type == 'asym':
        if dataset == 'mnist':
            train_noisy_labels, actual_noise_rate = noisify_mnist_asymmetric(
                train_labels, noise_rate, seed=seed)
        elif dataset == 'cifar10':
            train_noisy_labels, actual_noise_rate = noisify_cifar10_asymmetric(
                train_labels, noise_rate, seed=seed)
        elif dataset == 'cifar100':
            train_noisy_labels, actual_noise_rate = noisify_cifar100_asymmetric(
                train_labels, noise_rate, seed=seed)
    return train_noisy_labels, actual_noise_rate



